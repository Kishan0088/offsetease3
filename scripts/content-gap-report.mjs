// Phase J2 — content-gap report. For each pillar, list intent slots that have no
// page yet, as a prioritised backlog. This is a BRIEF for humans — it does not
// write pages. Run: node scripts/content-gap-report.mjs  → docs/content-gap-report.md
import { readdirSync, writeFileSync } from "node:fs";

const slugs = new Set(readdirSync(".")
  .filter((f) => f.endsWith(".html") || f.endsWith(".njk"))
  .map((f) => f.replace(/\.(html|njk)$/, "")));

const pillars = {
  ISCC: { hub: "iscc", schemes: ["EU", "PLUS", "CORSIA"] },
  CBAM: { hub: "cbam", schemes: [] },
  EUDR: { hub: "eudr", schemes: [] },
};
// intent slots ranked bottom-funnel first
const slots = [
  ["{p} certification cost / pricing", "transactional", (p) => `${p}-certification-cost`],
  ["{p} consultant / consulting {country}", "transactional", (p) => `${p}-consultant`],
  ["{p} requirements for {industry}", "problem-aware", (p) => `${p}-requirements`],
  ["{p} vs {alternative}", "commercial", (p) => `${p}-vs`],
  ["{p} checklist", "problem-aware", (p) => `${p}-checklist`],
  ["{p} in {country} (regional)", "transactional", (p) => `${p}-{country}`],
  ["{p} audit process", "problem-aware", (p) => `${p}-audit-process`],
  ["{p} timeline", "informational", (p) => `${p}-timeline`],
];

let md = `# Content-gap backlog (Phase J)\n\n`;
md += `> Generated by \`scripts/content-gap-report.mjs\`. Prioritised bottom-funnel first.\n`;
md += `> Each row is a brief for a human writer — **do not auto-generate** (compliance-sensitive).\n`;
md += `> Regional/regulatory pages: every date/threshold needs a \`VERIFY\` against the issuing body.\n\n`;

for (const [name, cfg] of Object.entries(pillars)) {
  md += `## ${name} (hub: /${cfg.hub})\n\n`;
  md += `| Priority | Intent slot | Funnel | Suggested slug | Status |\n|---|---|---|---|---|\n`;
  let i = 1;
  for (const [label, funnel, slugFn] of slots) {
    const candidate = slugFn(cfg.hub);
    md += `| ${i++} | ${label.replace("{p}", name)} | ${funnel} | \`/${candidate}\` | ${slugs.has(candidate) ? "✅ exists" : "⬜ gap"} |\n`;
  }
  md += `\n`;
}
md += `## Notes\n- Only 3 pillars receive net-new content until one reaches page 1 (Phase J1).\n- Regional slots feed Phase I (India/SEA/ME only, per strategic gate).\n`;
writeFileSync("docs/content-gap-report.md", md);
console.log("J: wrote docs/content-gap-report.md");
